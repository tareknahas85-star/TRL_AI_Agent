// Google Apps Script the user pastes into their own Gmail account (script.google.com). It only READS new inbox mail
// and POSTs plain text to the user's gate with a write-only key. It never sends, deletes or changes anything.
export function mailScript(gateUrl: string, key: string, src: string): string {
  return [
    '// TRL AI Agent - read-only mailbox link. Paste in script.google.com (signed in to the Gmail you want to link),',
    '// run installTrigger() once and approve the permission. It checks new mail every minute.',
    "const GATE = '" + gateUrl + "';",
    "const KEY = '" + key + "';",
    "const SRC = '" + src + "';",
    '',
    'function installTrigger() {',
    '  ScriptApp.getProjectTriggers().forEach((t) => ScriptApp.deleteTrigger(t));',
    "  ScriptApp.newTrigger('pushMail').timeBased().everyMinutes(1).create();",
    "  PropertiesService.getScriptProperties().setProperty('LAST', String(Date.now()));",
    '}',
    '',
    'function pushMail() {',
    '  const props = PropertiesService.getScriptProperties();',
    "  const last = Number(props.getProperty('LAST') || Date.now());",
    '  const out = [];',
    '  let newest = last;',
    "  GmailApp.search('in:inbox newer_than:1d', 0, 15).forEach((th) => {",
    '    th.getMessages().forEach((m) => {',
    '      const t = m.getDate().getTime();',
    '      if (t <= last) return;',
    '      newest = Math.max(newest, t);',
    '      out.push({ id: m.getId(), from: m.getFrom(), subject: m.getSubject(), date: m.getDate().toISOString(), body: m.getPlainBody().slice(0, 6000) });',
    '    });',
    '  });',
    '  if (!out.length) return;',
    '  out.sort((a, b) => (a.date < b.date ? -1 : 1));',
    "  const r = UrlFetchApp.fetch(GATE + '/mail', {",
    "    method: 'post',",
    "    contentType: 'application/json',",
    "    headers: { 'x-mail-key': KEY, 'x-mail-src': SRC },",
    '    payload: JSON.stringify(out.slice(0, 10)),',
    '    muteHttpExceptions: true,',
    '  });',
    "  if (r.getResponseCode() === 200) props.setProperty('LAST', String(newest));",
    "  else console.error('gate ' + r.getResponseCode());",
    '}',
    ''
  ].join('\n')
}
